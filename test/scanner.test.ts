import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, symlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { expect, test } from 'vitest';
import { PathError } from '../src/errors.js';
import { isExcludedPath, resolveInRoot, scan } from '../src/scanner/index.js';

const FILES: Record<string, string | Buffer> = {
  'src/app.ts': 'export const a = 1;\n',
  'docs/notes.md': '# Notes\n',
  'node_modules/dep/index.js': 'module.exports = 1;\n',
  'dist/app.js': 'var a = 1;\n',
  'vendor/lib/lib.go': 'package lib\n',
  'package-lock.json': '{}\n',
  'yarn.lock': 'lock\n',
  'go.sum': 'sum\n',
  'public/app.min.js': 'var a=1;\n',
  'public/packed.js': `var a=${'1+'.repeat(3000)}1;`,
  'api/service.pb.go': 'package api\n',
  'api/zz_gen.go': '// Code generated by protoc-gen-go. DO NOT EDIT.\npackage api\n',
  '.env': 'SECRET=1\n',
  '.env.local': 'SECRET=2\n',
  'certs/server.pem': 'pem\n',
  'certs/server.key': 'key\n',
  id_rsa: 'private\n',
  'id_rsa.pub': 'public\n',
  'assets/logo.png': Buffer.from([0x89, 0x50, 0x4e, 0x47, 0, 0, 0, 1]),
  'data/big.txt': 'line\n'.repeat(120 * 1024),
  'empty.txt': '',
};
const KEPT = ['docs/notes.md', 'src/app.ts'];

function makeRepo(): string {
  const root = mkdtempSync(join(tmpdir(), 'remimem-scan-'));
  for (const [path, content] of Object.entries(FILES)) {
    mkdirSync(dirname(join(root, path)), { recursive: true });
    writeFileSync(join(root, path), content);
  }
  return root;
}

test('without git: secrets, binaries, vendored, generated, and oversized files are excluded', () => {
  const root = makeRepo();
  expect(scan(root).map((f) => f.path)).toEqual(KEPT);
});

test('with git: the same excludes apply and .gitignore is honored', () => {
  const root = makeRepo();
  writeFileSync(join(root, 'scratch.ts'), 'export {};\n');
  writeFileSync(join(root, '.gitignore'), 'scratch.ts\n');
  execFileSync('git', ['init', '-q'], { cwd: root });
  // Force-add excluded files to prove the scanner does not rely on .gitignore for them.
  execFileSync('git', ['add', '-f', '.env', 'node_modules', 'certs', 'src'], { cwd: root });
  expect(scan(root).map((f) => f.path)).toEqual(['.gitignore', ...KEPT]);
});

test('the size limit is configurable', () => {
  const root = makeRepo();
  expect(scan(root, { maxFileSizeKb: 1024 }).map((f) => f.path)).toContain('data/big.txt');
});

test('include and exclude globs narrow the scan', () => {
  const root = makeRepo();
  expect(scan(root, { exclude: ['docs/**'] }).map((f) => f.path)).toEqual(['src/app.ts']);
  expect(scan(root, { include: ['**/*.md'] }).map((f) => f.path)).toEqual(['docs/notes.md']);
  // Built-in excludes still win over an include glob.
  expect(scan(root, { include: ['**/.env*', 'src/**'] }).map((f) => f.path)).toEqual([
    'src/app.ts',
  ]);
});

test('isExcludedPath covers the documented categories', () => {
  for (const path of [
    'a/node_modules/b.js',
    '.env.production',
    'k/id_ed25519',
    'x/y.min.css',
    'poetry.lock',
  ]) {
    expect(isExcludedPath(path), path).toBe(true);
  }
  for (const path of ['src/environment.ts', 'src/keys.ts', 'distance.py', 'lock.go']) {
    expect(isExcludedPath(path), path).toBe(false);
  }
});

test('resolveInRoot rejects paths that leave the root, including through symlinks', () => {
  const root = makeRepo();
  expect(resolveInRoot(root, 'src/app.ts')).toMatch(/app\.ts$/);
  expect(() => resolveInRoot(root, '../outside.txt')).toThrow(PathError);
  expect(() => resolveInRoot(root, join(tmpdir(), 'elsewhere.txt'))).toThrow(PathError);
  const outside = mkdtempSync(join(tmpdir(), 'remimem-outside-'));
  writeFileSync(join(outside, 'secret.txt'), 'secret\n');
  try {
    symlinkSync(join(outside, 'secret.txt'), join(root, 'link.txt'));
  } catch {
    return; // creating symlinks needs extra rights on Windows
  }
  expect(() => resolveInRoot(root, 'link.txt')).toThrow(PathError);
  expect(scan(root).map((f) => f.path)).not.toContain('link.txt');
});
